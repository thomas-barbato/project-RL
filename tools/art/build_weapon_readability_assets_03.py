"""Freeze approved weapon pixels and poses into embedded runtime resources."""
from pathlib import Path
import colorsys
import hashlib
import json

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT/'assets/sprites/weapon-readability-03'
DOC = ROOT/'docs/reviews/weapon-readability-02'


def read(path):
    return json.loads(path.read_text('utf-8'))


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2)+'\n', 'utf-8')


def main():
    first = read(ROOT/'docs/reviews/weapon-readability-01/acceptance.json')
    second = read(DOC/'acceptance.json')
    entries = first['accepted_candidates']+second['accepted_candidates']
    assert {c['model'] for c in entries} == {2,17,23,31,51,66}
    DEST.mkdir(parents=True, exist_ok=True)
    catalog = ['// Generated by build_weapon_readability_assets_03.py; accepted waves 01 and 02.',
               'const WEAPONS: &[ReviewedWeapon] = &[']
    for c in entries:
        for field in ['source', 'native']:
            assert sha(ROOT/c[field]) == c[field+'_sha256'], c['id']
        native = Image.open(ROOT/c['native']).convert('RGBA')
        image = Image.new('RGBA', (128,128))
        # Direct copy: do not blend, resize or repaint approved native pixels.
        image.paste(native, tuple(c['origin']))
        asset = DEST/f'{c["id"]}.png'
        image.save(asset, optimize=True)
        # Same author-time membership policy as the existing finished weapon
        # catalogue (material_map(...,0)); neutral steel/outlines stay fixed.
        mask = Image.new('RGBA', image.size)
        values = []
        for r,g,b,a in image.get_flattened_data():
            _h,l,s = colorsys.rgb_to_hls(r/255,g/255,b/255)
            values.append((int(s>.13 and .14<l<.84),0,0,255) if a else (0,0,0,0))
        mask.putdata(values)
        mask_path = DEST/f'{c["id"]}-materials.png'
        mask.save(mask_path, optimize=True)
        c['runtime'] = str(asset.relative_to(ROOT)).replace('\\','/')
        c['runtime_sha256'] = sha(asset)
        c['material_mask'] = str(mask_path.relative_to(ROOT)).replace('\\','/')
        c['material_mask_sha256'] = sha(mask_path)
        def vec(v):
            return '['+', '.join(f'{x:.8f}' for x in v)+']'
        catalog.extend([
            '    ReviewedWeapon {',
            f'        model: {c["model"]},',
            f'        bytes: include_bytes!("../{c["runtime"]}"),',
            f'        material: include_bytes!("../{c["material_mask"]}"),',
            f'        anchor: {vec(c["anchor"])},',
            f'        support: {vec(c["support"])},',
            f'        angle: {c["angle"]:.8f},',
            f'        grip_angle: {c["grip_angle"]:.8f},',
            f'        scales: {vec(c["scales"])},',
            f'        shift: {vec(c["shift_from_palms"])},',
            '    },',
        ])
    catalog.extend(['];',''])
    (ROOT/'src/game_art_weapon_readability_catalog.rs').write_text('\n'.join(catalog), 'utf-8')
    manifest = dict(review_id='WEAPON-READABILITY03-INTEGRATION', native_tile=64, canvas=128,
                    approvals=['docs/reviews/weapon-readability-01/acceptance.json',
                               'docs/reviews/weapon-readability-02/acceptance.json'],
                    entries=entries, runtime_source='embedded assets only',
                    painted_variants='existing equipment ramps, same material-label policy',
                    other_models='preserved', game_rules_changes=False)
    write(DEST/'manifest.json', manifest)
    print(json.dumps(dict(weapons=len(entries), embedded_images=len(entries)*2,
                         source_pixels='byte-identical native copies', runtime_artifact_dependencies=0)))


if __name__ == '__main__':
    main()
