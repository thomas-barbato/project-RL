"""Assemble image_gen body modules with one immutable head for visual review.

Semantic drawing is generated by image_gen. This only frames components,
composes the requested head/body layers and lays out numbered review sheets.
"""
from pathlib import Path
import hashlib
import html
import json
import shutil

from PIL import Image, ImageDraw

from prepare_class_readability_review_01 import ROOT, SOURCES, OUT, REVIEW, STREET, core_box, font, native_image, sha, write_json
from prepare_bastion_armor_wave_01 import comparison

WAVE = 'bastion-wave-01'
DEST, DOCS, ART = OUT/WAVE, REVIEW/WAVE, SOURCES/WAVE
NECK_Y = 12
LABELS = ['Très légère', 'Légère', 'Interméd.', 'Lourde', 'Très lourde']


def pixels_hash(image):
    return hashlib.sha256(image.tobytes()).hexdigest()


def compose_body(source, head):
    framed, measurements = native_image(source, 50)
    body = Image.new('RGBA', (64, 64))
    body.paste(framed.crop((0, NECK_Y, 64, 64)), (0, NECK_Y))
    assembled = body.copy()
    assembled.paste(head.crop((0, 0, 64, NECK_Y)), (0, 0))
    return body, assembled, measurements


def native_board(sprites):
    board = Image.new('RGB', (400, 348), '#152025')
    draw = ImageDraw.Draw(board)
    draw.text((9, 9), 'Bastion · tenues complètes · 64 × 64 natifs', font=font(14), fill='#efddbd')
    for i, label in enumerate(LABELS):
        draw.text((i*80+7, 35), f'{i+1:02d} · {label}', font=font(10), fill='#d4dfdc')
    for row, (label, color) in enumerate([('Sol sombre', '#343b3f'), ('Sol clair', '#858478'), ('Pénombre', '#12181d')]):
        y = 72+row*90
        draw.rectangle((4, y-3, 396, y+66), fill=color)
        for i, sprite in enumerate(sprites):
            board.paste(sprite, (i*80+8, y), sprite)
        draw.text((9, y+68), label, font=font(11), fill='#acbfc3')
    board.save(DEST/'full-body-native64.png')


def zoom_board(sprites):
    board = Image.new('RGB', (1040, 263), '#243036')
    draw = ImageDraw.Draw(board)
    draw.text((12, 8), 'Zoom entier ×3 · cinq fois la même tête', font=font(17), fill='#efddbd')
    for i, sprite in enumerate(sprites):
        enlarged = sprite.resize((192, 192), Image.Resampling.NEAREST)
        board.paste(enlarged, (8+i*208, 38), enlarged)
        draw.text((12+i*208, 234), f'{i+1:02d} · {LABELS[i]}', font=font(13), fill='#d3dedc')
    board.save(DEST/'full-body-zoom-x3.png')


def scene_board(sprites):
    street = Image.open(STREET).convert('RGBA')
    # Same empty road patch as the earlier class review; no actor is erased.
    patch = street.crop((80, 160, 400, 288))
    board = Image.new('RGB', (400, 186), '#152025')
    draw = ImageDraw.Draw(board)
    draw.text((9, 8), 'Même sol · montage de revue à taille native', font=font(14), fill='#efddbd')
    for i, sprite in enumerate(sprites):
        x = i*80
        board.paste(patch.crop((40+i*30, 16, 120+i*30, 144)), (x, 36))
        board.paste(sprite, (x+8, 68), sprite)
        draw.text((x+32, 167), f'{i+1:02d}', font=font(12), fill='#d3dedc')
    board.save(DEST/'full-body-scene-native64.png')


def main():
    for folder in (DEST, DOCS, ART):
        folder.mkdir(parents=True, exist_ok=True)
    if (DOCS/'acceptance.json').exists():
        raise SystemExit('Accepted wave is frozen; create a new revision.')
    spec = json.loads((DOCS/'progression-prompts.json').read_text('utf-8'))
    protected = [ROOT/'assets/sprites/art-finish-01/FIN-01.png', ROOT/'content/core/classes/bastion.json5']
    before = {p.relative_to(ROOT).as_posix():sha(p) for p in protected}
    reference, reference_measurements = native_image(ROOT/spec['head_reference'], 58)
    head = Image.new('RGBA', (64, 64))
    head.paste(reference.crop((0, 0, 64, NECK_Y)), (0, 0))
    head_path = ART/'BA-W01-common-head-native64.png'
    head.save(head_path)
    region_hash = pixels_hash(head.crop((0, 0, 64, NECK_Y)))
    entries, sprites = [], []
    for entry in spec['entries']:
        cid = entry['candidate_id']
        source = ART/(cid+'-body-source.png')
        shutil.copyfile(entry['generated_file'], source)
        if entry.get('superseded_attempt'):
            old = entry['superseded_attempt']
            shutil.copyfile(old['generated_file'], ART/(old['candidate_id']+'-body-source.png'))
        # Explicit ownership: head rows [0,12), body rows [12,64).
        # This prevents generated neck-edge antialias from modifying the face.
        body, assembled, measurements = compose_body(source, head)
        assert pixels_hash(assembled.crop((0, 0, 64, NECK_Y)))==region_hash
        bounds = core_box(assembled)
        assert bounds[1]==4 and bounds[3]==62 and bounds[0]>0 and bounds[2]<64, bounds
        body_path, final_path = DEST/(cid+'-body-native64.png'), DEST/(cid+'-native64.png')
        body.save(body_path); assembled.save(final_path)
        sprites.append(assembled)
        entries.append({
            'number':entry['number'], 'candidate_id':cid, 'label':entry['label'],
            'class_id':'core:bastion', 'item_id':None, 'status':'awaiting_visual_approval',
            'source':source.relative_to(ROOT).as_posix(), 'source_sha256':sha(source),
            'body_layer':body_path.relative_to(ROOT).as_posix(), 'body_layer_sha256':sha(body_path),
            'native':final_path.relative_to(ROOT).as_posix(), 'native_sha256':sha(final_path),
            'head_region_sha256':region_hash, 'head_layer':head_path.relative_to(ROOT).as_posix(),
            'measurements':measurements, 'assembled_core_box':list(bounds),
            'attachment_points':{'head_center_x':32, 'neck_seam_y':NECK_Y, 'foot_baseline_y':61},
            'weapon_anchors_and_poses':'pending_after_visual_review',
        })
    regions = {'hands_forearms_left':(8, 18, 24, 43), 'hands_forearms_right':(40, 18, 56, 43),
               'legs':(18, 36, 47, 54), 'boots':(16, 52, 49, 64)}
    differences = {name:[pixels_hash(sprite.crop(box)) for sprite in sprites] for name, box in regions.items()}
    assert all(len(set(values))==5 for values in differences.values()), differences
    assert all(sha(ROOT/path)==digest for path, digest in before.items())
    native_board(sprites); zoom_board(sprites); scene_board(sprites)
    data = {'review_id':'BASTION-W01', 'revision':'r02-full-body-progression', 'date':'2026-10-21',
        'status':'awaiting_individual_visual_review', 'class_id':'core:bastion', 'class_theme':'melee',
        'torso_visual_scope':'complete_outfit_below_head_including_arms_hands_legs_boots',
        'head_source':spec['head_reference'], 'head_source_sha256':sha(ROOT/spec['head_reference']),
        'head_layer':head_path.relative_to(ROOT).as_posix(), 'head_layer_sha256':sha(head_path),
        'reference_measurements':reference_measurements, 'entries':entries,
        'workflow':{'one_class_at_a_time':True, 'user_visual_review_before_next_wave':True,
                    'other_classes_started':False, 'integration_authorized':False},
        'scope_limits':{'new_item_names_or_stats':False, 'item_catalogue_assignments':'pending',
                        'numeric_weight_or_melee_bonuses':'not_defined', 'weapon_poses_validated':False,
                        'head_pixels_newly_accepted':False, 'runtime_integration':False},
        'checks':{'candidate_count':5, 'native_size':[64, 64], 'shared_head_identical_rgba_pixels':True,
                  'shared_head_region':[0, 0, 64, NECK_Y], 'head_region_sha256':region_hash,
                  'hands_legs_boots_regions_distinct_for_all_five':True, 'region_hashes':differences,
                  'source_alpha_retained':True, 'framing_isotropic':True, 'foot_baseline_y':61,
                  'all_assembled_heights':58, 'active_game_hashes_unchanged':before,
                  'scene_is_montage_not_engine_validation':True}}
    write_json(DOCS/'progression.json', data)
    pilot_html = ''
    pilot_path = DOCS/'readability-pilot-prompt.json'
    if pilot_path.exists():
        pilot = json.loads(pilot_path.read_text('utf-8'))
        cid = pilot['candidate_id']
        source = ART/(cid+'-body-source.png')
        shutil.copyfile(pilot['generated_file'], source)
        body, assembled, measurements = compose_body(source, head)
        assert pixels_hash(assembled.crop((0, 0, 64, NECK_Y)))==region_hash
        bounds = core_box(assembled)
        assert bounds[1]==4 and bounds[3]==62 and bounds[0]>0 and bounds[2]<64
        final_path = DEST/(cid+'-native64.png')
        body.save(DEST/(cid+'-body-native64.png'))
        assembled.save(final_path)
        comparison([sprites[-1], assembled], ['05 · détaillée r02', '05 · simplifiée r03'],
            DEST/'readability-pilot-native64.png', 'Très lourde · comparaison en 64 × 64')
        zoom = Image.new('RGB', (440, 252), '#243036')
        draw = ImageDraw.Draw(zoom)
        draw.text((12, 8), 'Même tête · zoom entier ×3', font=font(16), fill='#efddbd')
        for i, (sprite, label) in enumerate(((sprites[-1], '05 · détaillée r02'), (assembled, '05 · simplifiée r03'))):
            enlarged = sprite.resize((192, 192), Image.Resampling.NEAREST)
            zoom.paste(enlarged, (14+i*220, 36), enlarged)
            draw.text((20+i*220, 228), label, font=font(12), fill='#c5d3d4')
        zoom.save(DEST/'readability-pilot-zoom-x3.png')
        write_json(DOCS/'readability-pilot.json', {
            'review_id':'BASTION-W01', 'candidate_id':cid, 'parent_candidate':pilot['parent_candidate'],
            'status':'awaiting_visual_review_before_propagation',
            'source':source.relative_to(ROOT).as_posix(), 'source_sha256':sha(source),
            'native':final_path.relative_to(ROOT).as_posix(), 'native_sha256':sha(final_path),
            'measurements':measurements, 'assembled_core_box':list(bounds),
            'head_region_sha256':region_hash, 'head_identical_to_all_five':True,
            'simplification':'larger armor masses, fewer internal divisions, removed fine texture',
            'other_four_outfits_simplified':False, 'runtime_integration':False})
        pilot_html = '''<h3>05 · Très lourde : essai de simplification</h3>
<p>La première version accumulait trop de petites plaques, attaches et textures pour 64 px. L’essai r03 privilégie les grandes masses et quelques articulations lisibles. La tête reste exactement identique.</p>
<div class="native-scroll"><img class="board" width="384" height="348" src="bastion-wave-01/readability-pilot-native64.png" alt="Très lourde détaillée r02 et essai simplifié r03, avec la même tête, en 64 × 64 sur trois fonds"></div>
<details><summary>Zoom entier ×3 de cet essai</summary><div class="native-scroll"><img class="board" width="440" height="252" src="bastion-wave-01/readability-pilot-zoom-x3.png" alt="Zoom entier ×3 : très lourde détaillée puis simplifiée"></div></details>
<p class="note">Essai à revoir avant d’appliquer ce niveau de simplification aux quatre autres tenues. Le gain de lisibilité et le degré de finition restent à juger.</p>
<h3>Progression complète · version de travail détaillée</h3>'''
        color_path = DOCS/'color-prompts.json'
        if color_path.exists():
            color_spec = json.loads(color_path.read_text('utf-8'))
            color_sprites, color_entries = [assembled], []
            for color in color_spec['entries']:
                color_id = color['candidate_id']
                color_source = ART/(color_id+'-body-source.png')
                shutil.copyfile(color['generated_file'], color_source)
                color_body, color_sprite, color_measurements = compose_body(color_source, head)
                assert pixels_hash(color_sprite.crop((0, 0, 64, NECK_Y)))==region_hash
                color_native = DEST/(color_id+'-native64.png')
                color_body.save(DEST/(color_id+'-body-native64.png'))
                color_sprite.save(color_native)
                color_sprites.append(color_sprite)
                base_alpha, variant_alpha = assembled.getchannel('A'), color_sprite.getchannel('A')
                intersection = sum(a>=128 and b>=128 for a,b in zip(base_alpha.tobytes(), variant_alpha.tobytes()))
                union = sum(a>=128 or b>=128 for a,b in zip(base_alpha.tobytes(), variant_alpha.tobytes()))
                color_entries.append({'candidate_id':color_id, 'label':color['label'],
                    'status':'awaiting_visual_approval', 'source':color_source.relative_to(ROOT).as_posix(),
                    'source_sha256':sha(color_source), 'native':color_native.relative_to(ROOT).as_posix(),
                    'native_sha256':sha(color_native), 'measurements':color_measurements,
                    'head_region_sha256':region_hash, 'head_identical_to_all_five':True,
                    'solid_alpha_intersection_over_union_vs_base':intersection/union,
                    'exact_plate_masks_and_runtime_palette_shader':'not_produced'})
            comparison(color_sprites, ['05 · Ivoire', '05 · Rouge', '05 · Bleue', '05 · Verte'],
                DEST/'colors-native64.png', 'Très lourde · palettes · 64 × 64 natifs')
            color_zoom = Image.new('RGB', (832, 258), '#243036')
            draw = ImageDraw.Draw(color_zoom)
            draw.text((12, 8), 'Plaques monochromes · même tête · zoom entier ×3', font=font(16), fill='#efddbd')
            for i, (sprite, label) in enumerate(zip(color_sprites, ['Ivoire', 'Rouge', 'Bleue', 'Verte'])):
                enlarged = sprite.resize((192, 192), Image.Resampling.NEAREST)
                color_zoom.paste(enlarged, (8+i*208, 36), enlarged)
                draw.text((14+i*208, 232), label, font=font(12), fill='#d3dedc')
            color_zoom.save(DEST/'colors-zoom-x3.png')
            write_json(DOCS/'colors.json', {'review_id':'BASTION-W01', 'parent_candidate':cid,
                'status':'palette_proposals_awaiting_visual_review', 'requested_plate_colors':['red','blue','green'],
                'same_model_not_three_new_models':True, 'head_identical_rgba_pixels':True,
                'monochromatic_means_one_plate_hue_with_value_shading':True,
                'entries':color_entries, 'runtime_integration':False})
            color_html = '''<h3 id="bastion-colors">05 · Plaques rouges, bleues et vertes</h3>
<p>Trois variantes du même modèle simplifié. Toutes les plaques prennent une seule teinte, avec des ombres et lumières pour le relief ; tissus, articulations et tête gardent leurs couleurs.</p>
<div class="native-scroll"><img class="board" width="384" height="348" src="bastion-wave-01/colors-native64.png" alt="Très lourde simplifiée : ivoire, rouge, bleue et verte, avec la même tête en 64 × 64 natifs"></div>
<details><summary>Zoom entier ×3 des couleurs</summary><div class="native-scroll"><img class="board" width="832" height="258" src="bastion-wave-01/colors-zoom-x3.png" alt="Zoom entier ×3 des variantes ivoire, rouge, bleue et verte"></div></details>
<p class="note">Ces couleurs ne créent ni trois modèles supplémentaires ni de nouvelles statistiques. Les dessins sont des propositions ; les masques de plaques et le rendu de palettes du jeu restent à préparer après revue.</p>'''
            all_colors_section = DEST/'all-colors-section.html'
            if all_colors_section.exists():
                color_html = all_colors_section.read_text('utf-8')
            pilot_html = pilot_html.replace('<h3>Progression complète', color_html+'<h3>Progression complète')
    rows = ''.join(f'<tr><td>{e["number"]}</td><td>{html.escape(e["label"])}</td><td>{text}</td></tr>' for e, text in zip(entries, [
        'Textile souple, bras dégagés, gants légers, chaussures courtes.',
        'Veste renforcée, protections souples, gants couvrants, genoux et chevilles protégés.',
        'Plaques articulées, brassards, gantelets, cuisses, tibias et bottes renforcés.',
        'Couverture presque intégrale, bras blindés, gantelets fermés et hautes protections de jambes.',
        'Blindage intégral de mêlée, épaules massives, gros gantelets et bottes en coque.']))
    section = '''<section id="bastion-wave-01"><h2>Vague 01 · Bastion · de très léger à très lourd</h2>
<p><strong>Cinq tenues complètes pour la mêlée.</strong> L’armure de torse habille tout le corps sauf la tête : bras, mains, jambes et bottes évoluent ensemble.</p>
<p class="note">Même tête et même augmentation sur les cinq modèles : une seule couche commune, identique au pixel près. Les anciens essais limités au haut du corps sont remplacés par cette proposition.</p>
'''+pilot_html+'''
<div class="native-scroll"><img class="board" width="400" height="348" src="bastion-wave-01/full-body-native64.png" alt="Bastion, cinq tenues complètes de très légère à très lourde en 64 × 64 natifs, avec la même tête"></div>
<details><summary>Zoom entier ×3 des cinq tenues</summary><div class="native-scroll"><img class="board" width="1040" height="263" src="bastion-wave-01/full-body-zoom-x3.png" alt="Zoom entier ×3 de la progression complète du Bastion, même visage et augmentation"></div></details>
<div class="native-scroll"><img class="board" width="400" height="186" src="bastion-wave-01/full-body-scene-native64.png" alt="Les cinq tenues du Bastion sur le sol de la rue, montage à taille native"></div>
<p class="note">Montage sur le sol d’une capture acceptée ; le nouvel éclairage moteur reste à vérifier après le choix des dessins.</p>
<table style="border-collapse:collapse;font-size:14px"><thead><tr><th>Réf.</th><th>Tenue</th><th>Progression visuelle</th></tr></thead><tbody>'''+rows+'''</tbody></table>
<p class="note">Très légère à très lourde désigne ici les apparences proposées, sans nouveaux chiffres ni bonus. Les noms d’objets et leur répartition dans le catalogue restent à définir. Les armes gardent leurs modèles communs aux classes.</p>
<p>Cette vague attend ta revue avant la suite. Aucun dessin n’est intégré au jeu.</p>
<p><a href="../../docs/reviews/class-readability-01/bastion-wave-01/REVIEW.md">Périmètre corrigé de la vague</a> · <a href="../../docs/reviews/class-readability-01/bastion-wave-01/progression-prompts.json">Prompts des cinq tenues</a> · <a href="../../docs/reviews/class-readability-01/bastion-wave-01/readability-pilot-prompt.json">Prompt image_gen de simplification</a></p></section>'''
    (DEST/'section.html').write_text(section, 'utf-8')
    # Keep the global prompt ledger complete for its latest Bastion reference.
    ledger_path = REVIEW/'prompts.json'
    ledger = json.loads(ledger_path.read_text('utf-8'))
    if not any(p['id']=='CL01-r04' for p in ledger):
        revisions = json.loads((DOCS/'prompts.json').read_text('utf-8'))['head_revisions']
        latest = next(p for p in revisions if p['id']=='CL01-r04')
        ledger.append({k:latest[k] for k in ('id', 'class_id', 'prompt', 'tool', 'transparent_background')})
        write_json(ledger_path, ledger)
    print(json.dumps({'review_id':data['review_id'], 'revision':data['revision'],
        'head_identical':True, 'body_regions_distinct':True,
        'native_widths':[e['assembled_core_box'][2]-e['assembled_core_box'][0] for e in entries]}))


if __name__=='__main__':
    main()
