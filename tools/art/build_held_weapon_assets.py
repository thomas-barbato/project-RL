"""Package or verify the accepted held-weapon rule without repainting artwork.

Default: rebuild layers with the native Rust compositor, then bind the models.
--finish: bind a just-completed native packaging run without rerunning it.
--check: verify sources, protected banks, generated bindings and packaged files.
"""
from pathlib import Path
import argparse
import ast
import hashlib
import json
import re
import subprocess

ROOT = Path(__file__).resolve().parents[2]
REVIEW = ROOT / 'docs/reviews/refonte-agent-2026-10-06/held-weapon-review-01'
OUT = ROOT / 'assets/sprites/held-native64'
CATALOG = ROOT / 'src/game_art_held_catalog.rs'


def read(path):
    return json.loads(path.read_text('utf-8'))


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def inputs():
    accepted = read(REVIEW / 'visual-acceptance-01.json')
    assert sha(REVIEW / 'review.json') == accepted['review_sha256']
    tree = ast.parse((ROOT / 'tools/archive/refonte-agent-2026-10-06/build_comic_catalogue_03.py').read_text('utf-8'))
    values = {n.targets[0].id: ast.literal_eval(n.value) for n in tree.body
              if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name)
              and n.targets[0].id in ('GUN_GRIPS', 'MELEE_GRIPS', 'HEAVY_SUPPORT')}
    catalog = read(ROOT / 'docs/reviews/refonte-agent-2026-10-06/comic-catalogue-review-03/catalogue.json')
    active = {e['id'] for e in read(REVIEW.parent / 'equipment-native64-01/review.json')['icons']}
    bindings = read(ROOT / 'assets/sprites/flat-agents/manifest.json')['weapons']
    entries = []
    for e in catalog['entries']:
        if e.get('content_id') not in active:
            continue
        heavy = e.get('family') in (10, 12, 13, 14)
        axe = e.get('family') == 3 and e.get('hold') == 'MeleeTwoHanded'
        if not (heavy or axe):
            continue
        number = int(e['review_id'][4:])
        binding = next(w for w in bindings if w['review_id'] == e['review_id'])
        grip = values['GUN_GRIPS' if heavy else 'MELEE_GRIPS'][number]
        support = values['HEAVY_SUPPORT'][number] if heavy else (0, 0)
        if number == 24:
            grip, support = (.34, .80), (.82, .85)
        entries.append(dict(id=e['content_id'], review_id=e['review_id'], model=binding['model'],
                            source=e['source_path'], source_sha256=sha(ROOT / e['source_path']),
                            kind=1 if heavy else 2, grip=list(grip), support=list(support),
                            previous_scale=binding['transform']['scale_native']))
    assert len(entries) == 34
    return dict(review_id=accepted['review_id'], entries=entries, expected_outfits=19, palettes=3,
                protected_files=read(REVIEW / 'review.json')['protected_runtime_files'])


def rust_catalog(manifest):
    lines = ['// Generated by tools/art/build_held_weapon_assets.py; HELD-WEAPON-64-01-ACCEPT01.',
             'const REVISED_GRIPS: &[Grip] = &[']
    for e in manifest['entries']:
        hands = repr(e['hands'])
        lines.append(f'    Grip {{ model: {e["model"]}, hands: {hands}, opposed: {str(e["opposed"]).lower()} }},')
    return '\n'.join(lines + ['];', ''])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--finish', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = inputs()
    if not args.check:
        (REVIEW / 'build-inputs.json').write_text(json.dumps(source, ensure_ascii=False, indent=2) + '\n', 'utf-8')
        if not args.finish:
            subprocess.run(['cargo', 'run', '--locked', '--example', 'package_held_weapons'], cwd=ROOT, check=True)
    else:
        assert read(REVIEW / 'build-inputs.json') == source
    manifest = read(OUT / 'manifest.json')
    assert manifest['verified_armor_palette_combinations'] == 1938
    for e, src in zip(manifest['entries'], source['entries'], strict=True):
        assert e['id'] == src['id'] and e['model'] == src['model']
        assert sha(ROOT / e['source']) == e['source_sha256']
        assert e['angle_degrees'] == (90 if src['kind'] == 2 else 0)
    for name, digest in source['protected_files'].items():
        assert sha(ROOT / name) == digest, name
    generated = rust_catalog(manifest)
    if args.check:
        # rustfmt may wrap the generated constants; compare semantic whitespace.
        def normalized(text):
            return re.sub(r',([}\]])', r'\1', ''.join(text.split()))
        assert normalized(CATALOG.read_text('utf-8')) == normalized(generated)
        assert manifest['weapons_sha256'] == sha(OUT / 'weapons-128.png')
    else:
        CATALOG.write_text(generated, 'utf-8')
        manifest['approved_by'] = str((REVIEW / 'visual-acceptance-01.json').relative_to(ROOT)).replace('\\', '/')
        manifest['weapons_sha256'] = sha(OUT / 'weapons-128.png')
        (OUT / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', 'utf-8')
    print(json.dumps({'models': len(manifest['entries']), 'armor_palette_combinations': 1938,
                      'original_banks_unchanged': len(source['protected_files']),
                      'runtime_png_bytes': (OUT / 'weapons-128.png').stat().st_size, 'check': args.check}))


if __name__ == '__main__':
    main()
