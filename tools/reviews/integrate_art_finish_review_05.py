"""Freeze and package the four exact ART-FINISH-05 drawings accepted by the player."""
import json
import shutil
from art_finish_batch_05 import ROOT, ART, DOC, sha, write


def main():
    files=[f'FIN-{n}.png' for n in range(28,32)]
    receipt=dict(review='ART-FINISH-05',date='2026-10-19',status='accepted',
        user_answer='Valider le lot complet',drawings=4,background_samples=12,scene_comparisons=2,
        approved_exports={name:sha(ART/'native'/name) for name in files},
        variants='014 A, 016 A, 006 A, 120 A; other variants unchanged')
    accepted=DOC/'acceptance.json'
    if accepted.exists(): assert json.loads(accepted.read_text('utf-8'))==receipt,'Frozen approval changed'
    else: write(accepted,receipt)
    dest=ROOT/'assets/sprites/art-finish-05';dest.mkdir(parents=True,exist_ok=True)
    for name in files:
        shutil.copyfile(ART/'native'/name,dest/name)
        assert sha(dest/name)==receipt['approved_exports'][name],name
    lines=['// Exact exports accepted in ART-FINISH-05; generated by integrate_art_finish_review_05.py.',
        "pub(super) fn bytes_05(name: &str) -> Option<&'static [u8]> {",'    Some(match name {']
    lines += [f'        "{name[:-4]}" => include_bytes!("../assets/sprites/art-finish-05/{name}"),' for name in files]
    lines += ['        _ => return None,','    })','}','']
    (ROOT/'src/game_art_finish_catalog_05.rs').write_text('\n'.join(lines),encoding='utf-8')
    print('Packaged 4 byte-identical accepted enemy drawings')


if __name__=='__main__': main()
