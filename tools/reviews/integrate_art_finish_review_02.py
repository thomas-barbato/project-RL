"""Package the exact ART-FINISH-02 exports approved on 19 October 2026."""
import json
import shutil
from art_finish_batch_02 import ROOT, ART, DOC, sha, write


def main():
    source = ART / 'native'
    files = [f'FIN-{i:02}.png' for i in range(14, 22)]
    files += [f'FIN-{i:02}-{pose}-{layer}.png' for i in range(14, 22)
              for pose in ['single', 'rifle'] for layer in ['body', 'weapon', 'fingers']]
    receipt = dict(review='ART-FINISH-02', date='2026-10-19',
                   user_answer='Valider le lot complet', status='accepted',
                   drawings=8, hand_configurations=24, scene_comparisons=4,
                   approved_exports={f: sha(source / f) for f in files})
    accepted = DOC / 'acceptance.json'
    if accepted.exists():
        assert json.loads(accepted.read_text('utf-8')) == receipt, 'Frozen approval changed'
    else:
        write(accepted, receipt)
    dest = ROOT / 'assets/sprites/art-finish-02'
    dest.mkdir(parents=True, exist_ok=True)
    for name in files:
        shutil.copyfile(source / name, dest / name)
        assert sha(dest / name) == receipt['approved_exports'][name]
    rust = ['// Exact exports accepted in ART-FINISH-02; generated by integrate_art_finish_review_02.py.',
            'pub(super) fn bytes_02(name: &str) -> Option<&\'static [u8]> {',
            '    Some(match name {']
    rust += [f'        "{f[:-4]}" => include_bytes!("../assets/sprites/art-finish-02/{f}"),' for f in files]
    rust += ['        _ => return None,', '    })', '}', '']
    (ROOT / 'src/game_art_finish_catalog_02.rs').write_text('\n'.join(rust), encoding='utf-8')
    print(f'Packaged {len(files)} byte-identical accepted exports')


if __name__ == '__main__':
    main()
