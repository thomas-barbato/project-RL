"""Package the exact ART-FINISH-01 exports approved on 19 October 2026.

No painting, resizing or new palette: copy only the thirteen accepted drawings,
twelve hand layers and five additional palettes actually shown in the review.
"""
from pathlib import Path
import hashlib
import json
import shutil

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / 'docs/reviews/refonte-histoire-2026-10-16/art-finish-review-01'
SOURCE = ROOT / 'assets/source-art/art-finish-review-01/native'
DEST = ROOT / 'assets/sprites/art-finish-01'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    files = [f'FIN-{i:02}.png' for i in range(1, 14)]
    files += [f'FIN-{i:02}-{pose}-{layer}.png' for i in [1, 2]
              for pose in ['single', 'rifle'] for layer in ['body', 'weapon', 'fingers']]
    files += [f'FIN-09-{color}.png' for color in ['blue', 'orange', 'green']]
    files += [f'FIN-10-{color}.png' for color in ['orange', 'green']]
    receipt = dict(review='ART-FINISH-01', date='2026-10-19',
                   user_answer='Valider le lot complet', status='accepted',
                   drawings=13, hand_configurations=6, palette_samples=7,
                   scene_comparisons=2, approved_exports={f: sha(SOURCE / f) for f in files},
                   unshown_exports_excluded=['FIN-10-blue.png'])
    accepted = DOC / 'acceptance.json'
    if accepted.exists():
        assert json.loads(accepted.read_text('utf-8')) == receipt, 'Frozen approval changed'
    else:
        accepted.write_text(json.dumps(receipt, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    DEST.mkdir(parents=True, exist_ok=True)
    for file in files:
        shutil.copyfile(SOURCE / file, DEST / file)
        assert sha(SOURCE / file) == sha(DEST / file)
    rust = ['// Exact exports accepted in ART-FINISH-01; generated by integrate_art_finish_review.py.',
            'pub(super) fn bytes(name: &str) -> Option<&\'static [u8]> {', '    Some(match name {']
    rust += [f'        "{f[:-4]}" => include_bytes!("../assets/sprites/art-finish-01/{f}"),' for f in files]
    rust += ['        _ => return None,', '    })', '}', '']
    (ROOT / 'src/game_art_finish_catalog.rs').write_text('\n'.join(rust), encoding='utf-8')
    print(f'Packaged {len(files)} byte-identical accepted exports')


if __name__ == '__main__':
    main()
